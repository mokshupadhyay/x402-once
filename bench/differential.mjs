// Differential run: the stock @x402/fetch wrapper and x402-once, same simulated seller, same calls, counting settlements.
// No chain, no wallet, no network: `npm run build && node bench/differential.mjs [--identical 1000] [--distinct 500]`.
// It answers: when many calls for one purchase overlap, how many payments settle?
import { writeFile, mkdir } from 'node:fs/promises';
import { wrapFetchWithPayment } from '@x402/fetch';
import { createPaidFetch, MemoryPaymentStore } from '../dist/index.js';
import { createFakeClient, createSimulatedMerchant, scriptedFaults } from '../dist/testing.js';

const arg = (name, fallback) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? Number(process.argv[i + 1]) : fallback;
};
const IDENTICAL = arg('identical', 1000);
const DISTINCT = arg('distinct', 500);
const URL_A = 'https://seller.test/api/report';

function build(kind, merchantOptions, paidOptions = {}) {
  const merchant = createSimulatedMerchant({ latencyMs: 5, ...merchantOptions });
  const client = createFakeClient('eip155:84532');
  const fetchFn =
    kind === 'stock'
      ? wrapFetchWithPayment(merchant.fetch, client)
      : createPaidFetch({ client, fetch: merchant.fetch, store: new MemoryPaymentStore(), ...paidOptions });
  return { merchant, fetchFn };
}

const ok = async (promise) => {
  try {
    return (await promise).status === 200;
  } catch {
    return false;
  }
};

const rows = [];
async function scenario(title, expectation, run) {
  for (const kind of ['stock', 'x402-once']) {
    const { merchant, result } = await run(kind);
    rows.push({ title, expectation, client: kind, ...result, settlements: merchant.settlementCount });
  }
}

await scenario(`${IDENTICAL} identical calls started together`, 'one purchase: 1 settlement', async (kind) => {
  const { merchant, fetchFn } = build(kind);
  const results = await Promise.all(Array.from({ length: IDENTICAL }, () => ok(fetchFn(URL_A))));
  return { merchant, result: { calls: IDENTICAL, delivered: results.filter(Boolean).length } };
});

await scenario(`${DISTINCT} different purchases started together (control)`, `${DISTINCT} settlements, one each`, async (kind) => {
  const { merchant, fetchFn } = build(kind);
  const results = await Promise.all(Array.from({ length: DISTINCT }, (_, i) => ok(fetchFn(`${URL_A}/${i}`))));
  return { merchant, result: { calls: DISTINCT, delivered: results.filter(Boolean).length } };
});

await scenario('response lost after settlement, then the app retries once', '1 settlement', async (kind) => {
  const { merchant, fetchFn } = build(kind, { faults: scriptedFaults('drop-after-settle'), serveOnReplay: true });
  const first = await ok(fetchFn(URL_A));
  const second = await ok(fetchFn(URL_A));
  return { merchant, result: { calls: 2, delivered: [first, second].filter(Boolean).length } };
});

await scenario('two buyers send the same request, no scope', '2 purchases would be right; 1 means they were merged', async (kind) => {
  const { merchant, fetchFn } = build(kind);
  const results = await Promise.all(['a', 'b'].map((t) => ok(fetchFn(URL_A, { headers: { Authorization: `Bearer ${t}` } }))));
  return { merchant, result: { calls: 2, delivered: results.filter(Boolean).length } };
});

await scenario('two buyers send the same request, scope = the buyer', '2 settlements, one each', async (kind) => {
  const { merchant, fetchFn } = build(kind, {}, { scope: (r) => r.headers.get('Authorization') ?? undefined });
  const results = await Promise.all(['a', 'b'].map((t) => ok(fetchFn(URL_A, { headers: { Authorization: `Bearer ${t}` } }))));
  return { merchant, result: { calls: 2, delivered: results.filter(Boolean).length } };
});

const lines = [
  '# Differential run: stock `@x402/fetch` vs `x402-once`',
  '',
  `Simulated seller (in process, 5 ms per request), same fake signer. Generated by \`node bench/differential.mjs\` on ${new Date().toISOString().slice(0, 10)}.`,
  'The "stock" rows for the scope scenarios do not use scope (the stock wrapper has no such option).',
  '',
  '| Scenario | Expected | Client | Calls | Delivered | Settlements |',
  '|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.title} | ${r.expectation} | ${r.client} | ${r.calls} | ${r.delivered} | ${r.settlements} |`),
  '',
];
await mkdir(new URL('./results/', import.meta.url), { recursive: true });
await writeFile(new URL('./results/differential.md', import.meta.url), lines.join('\n'));
console.log(lines.join('\n'));
